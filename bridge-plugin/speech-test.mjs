// 口播抽取的单元测试：node speech-test.mjs
import { 挑要说的话 } from './index.js'

const 用例 = [
  {
    名: '约定口播优先',
    输: '先说结论：这次跑通了。\n\n口播：本鲸弄好啦，你试试看。\n\n详细步骤一二三……',
    期: '本鲸弄好啦，你试试看。',
  },
  {
    名: '口播太长要切',
    输: '口播：' + '本鲸今天把语音、录音、转写、还有桌宠那边的桥全都接好了，也顺手把气泡改短了，你随便说点什么试试。',
    期: (s) => s.length <= 40,
  },
  {
    名: '没口播就取第一句',
    输: '**搞定了**。剩下的明天再说，`code` 和 https://example.com 都不该念出来。',
    期: '搞定了。',
  },
  {
    名: '代码块不进嘴',
    输: '```bash\ndotnet build\n```\n好了，能跑了。',
    期: '好了，能跑了。',
  },
  {
    名: '全角冒号也行',
    输: '口播: 唔，本鲸在。',
    期: '唔，本鲸在。',
  },
  {
    名: '空的不念',
    输: '   \n\n',
    期: '',
  },
]

let 过 = 0
for (const c of 用例) {
  const 得 = 挑要说的话(c.输)
  const 行 = typeof c.期 === 'function' ? c.期(得) : 得 === c.期
  console.log(`${行 ? 'PASS' : 'FAIL'} ${c.名} → 「${得}」`)
  if (行) 过++
}
console.log(`\n${过}/${用例.length}`)
process.exit(过 === 用例.length ? 0 : 1)
